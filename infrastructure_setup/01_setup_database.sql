-- Set context
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS WORKSHOP_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60            -- Automatically suspends after 1 minute of inactivity
    AUTO_RESUME = TRUE           -- Automatically wakes up when a query runs
    INITIALLY_SUSPENDED = TRUE;  -- Starts suspended to save credits

-- Create the Database and Schema
CREATE DATABASE IF NOT EXISTS WORKSHOP_DB;
CREATE SCHEMA IF NOT EXISTS WORKSHOP_DB.RAW;

-- Optional but recommended: Create a specific role for the pipeline
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS WORKSHOP_INGESTION_ROLE;

-- Grant permissions to the role
GRANT USAGE ON WAREHOUSE WORKSHOP_WH TO ROLE WORKSHOP_INGESTION_ROLE;
GRANT USAGE ON DATABASE WORKSHOP_DB TO ROLE WORKSHOP_INGESTION_ROLE;
GRANT USAGE ON SCHEMA WORKSHOP_DB.RAW TO ROLE WORKSHOP_INGESTION_ROLE;
GRANT CREATE TABLE ON SCHEMA WORKSHOP_DB.RAW TO ROLE WORKSHOP_INGESTION_ROLE;